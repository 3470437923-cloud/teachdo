/* ---------- 搜索 ---------- */
TD.MAJORS.allMajors = function(){
  const out = [];
  Object.keys(this.categories).forEach(cat=>{
    this.categories[cat].forEach(m=>out.push({major:m, cat}));
  });
  return out;
};
TD.MAJORS.search = function(q){
  if(!q) return this.allMajors();
  q = q.toLowerCase();
  return this.allMajors().filter(m=>m.major.toLowerCase().includes(q));
};
TD.MAJORS.coursesOf = function(major){
  return this.courses[major] || [];
};
TD.MAJORS.searchCourses = function(major, q){
  const list = this.coursesOf(major);
  if(!q) return list;
  q = q.toLowerCase();
  return list.filter(c=>c.course.toLowerCase().includes(q) || c.topics.some(t=>t.toLowerCase().includes(q)));
};
